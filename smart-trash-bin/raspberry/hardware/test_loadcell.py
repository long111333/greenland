"""HX711 bench calibration: validate samples, save EEPROM and project coefficients."""
from __future__ import annotations
import argparse
import json
import logging
import math
import statistics
import struct
import time
from datetime import datetime, timezone
from pathlib import Path
from arduino_client import ArduinoClient, ArduinoError

PROJECT_ROOT = Path(__file__).resolve().parents[2]


def check_weight_support(client):
    try:
        return client.get_weight()
    except ArduinoError as error:
        if "INVALID_COMMAND" in str(error):
            raise ArduinoError(
                "Arduino firmware does not support GET_WEIGHT. Upload this project's "
                "HX711 firmware to the selected port, then rerun test_loadcell.py "
                "(DOUT=D4, SCK=D5). No calibration was written."
            ) from error
        raise


def float32(number):
    return struct.unpack("<f", struct.pack("<f", number))[0]


def collect_samples(client, count, timeout=None, after_sequence=None):
    readings, sequence = [], after_sequence
    deadline = time.monotonic() + (max(10.0, count * 0.5) if timeout is None else timeout)
    while len(readings) < count:
        if time.monotonic() >= deadline:
            raise TimeoutError("HX711: insufficient fresh samples; check DOUT=D4, SCK=D5, power and bridge wiring")
        data = client.get_weight()
        if (data.get("healthy") is True and type(data.get("raw")) is int
                and -8388608 < data["raw"] < 8388607
                and type(data.get("sample_seq")) is int and data["sample_seq"] != sequence):
            sequence = data["sample_seq"]
            readings.append(data["raw"])
            print(f"Sample {len(readings)}/{count}: raw={data['raw']}")
        time.sleep(0.06)
    return readings


def calculate_calibration(empty, loaded, known_grams):
    if not math.isfinite(known_grams) or known_grams <= 0:
        raise ValueError("Known weight must be positive grams")
    if len(empty) < 5 or len(loaded) < 5:
        raise ValueError("At least 5 samples per stage required")
    if any(type(value) is not int or not -8388608 < value < 8388607 for value in (*empty, *loaded)):
        raise ValueError("Invalid or saturated ADC sample")
    zero_mean, load_mean = statistics.mean(empty), statistics.mean(loaded)
    span = load_mean - zero_mean
    if abs(span) < 100:
        raise ValueError("Span below 100 ADC counts; check bridge/mechanics or use a larger known mass")
    noise = max(statistics.pstdev(empty), statistics.pstdev(loaded))
    if noise / abs(span) > 0.005:
        raise ValueError("Unstable samples (>0.5% of span); remove vibration and repeat")
    offset = round(zero_mean)
    factor = float32((load_mean - offset) / (known_grams / 1000.0))
    if not math.isfinite(factor) or not 1 < abs(factor) <= 1e12:
        raise ValueError("Calculated factor is out of range")
    return {"calibrated": True, "factor": factor, "offset": offset,
            "known_grams": known_grams, "empty_mean": zero_mean, "loaded_mean": load_mean,
            "span_counts": span, "noise_std_counts": noise,
            "empty_samples": empty, "loaded_samples": loaded}


def validate_weight(result, readings):
    expected = result["known_grams"] / 1000.0
    values = [(value - result["offset"]) / result["factor"] for value in readings]
    tolerance = max(0.003, expected * 0.02)
    if not readings or max(abs(value - expected) for value in values) > tolerance:
        raise ValueError("Independent verification exceeds max(3g, 2% of known mass); coefficients not applied")
    result["verification_samples"] = readings
    result["verified_mean_kg"] = statistics.mean(values)
    result["verification_tolerance_kg"] = tolerance


def write_project_calibration(result, project_root=PROJECT_ROOT):
    """Update generated load-cell files only; leave unrelated config unchanged."""
    factor, offset = result["factor"], result["offset"]
    calibrated = result.get("calibrated", True)
    if not math.isfinite(factor) or (calibrated and not 1 < abs(factor) <= 1e12):
        raise ValueError("Cannot save invalid factor")
    if type(offset) is not int or not -8388608 <= offset <= 8388607:
        raise ValueError("Cannot save invalid offset")
    factor_text = format(float32(factor), ".9g")
    if "." not in factor_text and "e" not in factor_text.lower():
        factor_text += ".0"
    timestamp = datetime.now(timezone.utc).isoformat()
    header = ("#pragma once\n// Generated by test_loadcell.py at " + timestamp + "\n"
              "namespace LoadCellCalibration {\n"
              f"constexpr bool CALIBRATED={'true' if calibrated else 'false'};\n"
              f"constexpr float FACTOR={factor_text}f; // ADC counts per kilogram\n"
              f"constexpr long OFFSET={offset};\n" + "}\n")
    root = Path(project_root)
    destinations = {
        root / "firmware/include/loadcell_calibration.h": header,
        root / "firmware/calibration/loadcell-calibration.json": json.dumps(
            {**result, "saved_at": timestamp, "factor_unit": "ADC counts/kg"}, ensure_ascii=False, indent=2),
    }
    archive = root / "firmware/calibration" / ("loadcell-" + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S-%f") + ".json")
    destinations[archive] = destinations[root / "firmware/calibration/loadcell-calibration.json"]
    previous = {path: path.read_bytes() if path.exists() else None for path in destinations}
    temporary, committed = [], []
    try:
        for path, content in destinations.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            temp = path.with_suffix(path.suffix + ".tmp")
            temp.write_text(content, encoding="utf-8")
            temporary.append((temp, path))
        for temp, path in temporary:
            temp.replace(path)
            committed.append(path)
    except Exception:
        for path in committed:
            if previous[path] is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(previous[path])
        raise
    finally:
        for temp, _ in temporary:
            temp.unlink(missing_ok=True)
    return list(destinations)


def calibrate(client, known_grams=None, samples=20, project_root=PROJECT_ROOT):
    status = client.get_status()
    if status.get("state") not in ("INIT", "IDLE"):
        raise ArduinoError("Calibration requires stopped INIT/IDLE; inspect mechanism and reset errors first")
    check_weight_support(client)
    print("No motor/servo commands will be sent. Empty the weighing platform.")
    if input("Platform empty and stable [y/N]: ").strip().lower() != "y":
        return None
    time.sleep(1.0)
    empty = collect_samples(client, samples)
    if known_grams is None:
        known_grams = float(input("Known mass in GRAMS (example 200): ").strip())
    if not math.isfinite(known_grams) or known_grams <= 0:
        raise ValueError("Known mass must be positive grams")
    if input(f"Place {known_grams:g} g within the load cell's rated capacity; stable [y/N]: ").strip().lower() != "y":
        return None
    time.sleep(1.0)
    loaded = collect_samples(client, samples)
    result = calculate_calibration(empty, loaded, known_grams)
    print("Keep known mass in place for an independent verification capture.")
    previous = client.get_weight().get("sample_seq")
    validate_weight(result, collect_samples(client, max(5, samples // 2), after_sequence=previous))
    print(f"Applying factor={result['factor']:.9g} counts/kg, offset={result['offset']}")
    client.set_scale(result["factor"], result["offset"])
    actual = client.get_weight()
    if (actual.get("calibrated") is not True or actual.get("offset") != result["offset"]
            or not math.isclose(actual.get("factor", float("nan")), result["factor"], rel_tol=2e-7)):
        raise ArduinoError("EEPROM completion received but coefficients differ; project files not changed")
    result["device_eeprom_saved"] = True
    try:
        paths = write_project_calibration(result, project_root)
    except Exception as error:
        raise ArduinoError(f"Device saved but project file save FAILED: {error}; factor={result['factor']}, offset={result['offset']}") from error
    for path in paths:
        print(f"Saved: {path}")
    print("Calibration is active and survives reboot. Future builds use generated project defaults.")
    return result


def main():
    parser = argparse.ArgumentParser(description="HX711 test and automatic project calibration")
    parser.add_argument("--port", help="COM5 or /dev/ttyACM0")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--read", action="store_true", help="Read continuously; no calibration writes")
    mode.add_argument("--tare", action="store_true", help="Empty-platform tare; save EEPROM and project defaults")
    parser.add_argument("--known-grams", type=float)
    parser.add_argument("--samples", type=int, default=20)
    args = parser.parse_args()
    if not 5 <= args.samples <= 100:
        parser.error("--samples must be 5..100")
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    with ArduinoClient(args.port) as client:
        if args.read:
            try:
                while True:
                    data = client.get_weight()
                    kg = data.get("weight_kg")
                    print(f"{kg:.3f} kg" if kg is not None else "UNKNOWN / calibration required", json.dumps(data))
                    time.sleep(0.25)
            except KeyboardInterrupt:
                return
        elif args.tare:
            check_weight_support(client)
            if input("Empty platform; authorize tare and save [y/N]: ").strip().lower() != "y":
                return
            client.tare_weight()
            actual = client.get_weight()
            result = {"factor": actual["factor"], "offset": actual["offset"],
                      "calibrated": actual["calibrated"], "device_eeprom_saved": True, "operation": "tare"}
            for path in write_project_calibration(result):
                print(f"Saved: {path}")
        else:
            calibrate(client, args.known_grams, args.samples)


if __name__ == "__main__":
    try:
        main()
    except (ArduinoError, TimeoutError, ValueError, OSError) as error:
        logging.error("%s", error)
        raise SystemExit(1)
    except KeyboardInterrupt:
        logging.warning("Interrupted. If SET_SCALE was already accepted, read actual coefficients before retrying.")
        raise SystemExit(130)
